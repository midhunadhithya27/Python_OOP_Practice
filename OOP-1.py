class goa:
    name = "$#$"
    drink = ""
    def party(self):
        print(f"lets party")
    def beach(self):
        print(f"let's enjoy the beach")

ramesh = goa()
suresh = goa()
ramesh.name = "Ramesh"
ramesh.drink = "Yes"
print("Name: ",ramesh.name)
print("Drink: ",ramesh.drink)
suresh.name = "suresh"
suresh.drink= "No"
print("Name: ",suresh.name)
print("Drink: ",suresh.drink)

ramesh.party()
suresh.beach()

